// Each kind writes an SVG from a committed run, with the given title, and
// the engine and headline kinds carry their panels and labels.
func TestChartWritesEachKind(t *testing.T) {
	t.Parallel()
	root := fixtureRoot(t)
	slo := filepath.Join(root, "docs", "slo.json")
	run := filepath.Join(root, tpRun)
	for kind, want := range map[string][]string{
		kindLatency:  {"Output tokens/s", "E2E p95 (s)", "SLO ≤ 15 s", "1,584 tok/s at c=64", "My title"},
		kindEngine:   {"KV cache in use (mean %)", "Requests waiting (mean)", "Preemptions in the window"},
		kindHeadline: {"Throughput profile", "1,584 tok/s at c=64", "Max compliant goodput"},
	} {
		out := filepath.Join(t.TempDir(), kind+".svg")
		args := []string{"chart", "--kind", kind, "--out", out, "--slo", slo, "--series", "baseline=Base"}
		if kind == kindLatency {
			args = append(args, "--title", "My title")
		}
		code, stdout, stderr := runBench(t, append(args, run)...)
		if code != 0 {
			t.Fatalf("%s: exit %d, stderr %q", kind, code, stderr)
		}
		if !strings.Contains(stdout, "wrote "+out) {
			t.Errorf("%s: stdout %q", kind, stdout)
		}
		b, err := os.ReadFile(out)
		if err != nil {
			t.Fatal(err)
		}
		for _, w := range want {
			if !strings.Contains(string(b), w) {
				t.Errorf("%s chart lacks %q", kind, w)
			}
		}
	}
}

