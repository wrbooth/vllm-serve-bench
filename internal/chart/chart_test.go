func TestStylesheetSwitchesEveryColorInDarkMode(t *testing.T) {
	t.Parallel()
	s := stylesheet()
	light, dark, ok := strings.Cut(s, "@media (prefers-color-scheme:dark){")
	if !ok {
		t.Fatal("no dark-mode block")
	}
	for _, tok := range tokens {
		if !strings.Contains(light, tok.light) {
			t.Errorf("light rules lack %s %s", tok.name, tok.light)
		}
		if !strings.Contains(dark, tok.dark) {
			t.Errorf("dark rules lack %s %s", tok.name, tok.dark)
		}
	}
	if strings.Contains(s, "var(") {
		t.Error("the stylesheet uses CSS custom properties, which SVG rasterizers ignore")
	}
}
