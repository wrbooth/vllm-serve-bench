// pathsOf returns the d attribute of every series line of a slot.
func pathsOf(svg, slot string) []string {
	var out []string
	for _, line := range strings.Split(svg, "\n") {
		if strings.Contains(line, `class="ln l`+slot+`"`) && strings.HasPrefix(line, `<path d="`) {
			d, _, _ := strings.Cut(strings.TrimPrefix(line, `<path d="`), `"`)
			out = append(out, d)
		}
	}
	return out
}

