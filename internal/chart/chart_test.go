func TestNiceTicksStepsOneTwoTwoPointFiveOrFiveTimesAPowerOfTen(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name  string
		top   float64
		ticks []float64
		step  float64
	}{
		// raw = 100/4 = 25; 2.5 × 10 = 25 ≥ 25, so step 25 and 4 steps.
		{"percent axis", 100, []float64{0, 25, 50, 75, 100}, 25},
		// raw = 4471.2/4 = 1117.8; 1 × 1000 < 1117.8 ≤ 2 × 1000.
		{"interactive tok/s", 4471.2, []float64{0, 2000, 4000, 6000}, 2000},
		// raw = 0.225; 2.5 × 0.1 = 0.25 ≥ 0.225; ceil(0.9/0.25) = 4.
		{"fractional", 0.9, []float64{0, 0.25, 0.5, 0.75, 1}, 0.25},
		// raw = 30/4 = 7.5; 5 × 1 < 7.5 ≤ 10 × 1: no multiplier fits, so 10.
		{"falls through to ten", 30, []float64{0, 10, 20, 30}, 10},
		{"empty axis", 0, []float64{0, 1}, 1},
		{"not a number", math.NaN(), []float64{0, 1}, 1},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			ticks, step := niceTicks(c.top)
			if step != c.step || len(ticks) != len(c.ticks) {
				t.Fatalf("niceTicks(%g) = %v step %g, want %v step %g", c.top, ticks, step, c.ticks, c.step)
			}
			for i := range ticks {
				if math.Abs(ticks[i]-c.ticks[i]) > 1e-9 {
					t.Fatalf("niceTicks(%g) = %v, want %v", c.top, ticks, c.ticks)
				}
			}
		})
	}
}

