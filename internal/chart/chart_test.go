func TestLog2AxisSpacesDoublingsEquallyInsideThePadding(t *testing.T) {
	t.Parallel()
	a := newLog2Axis(1, 256, 100, 900)
	step := a.at(2) - a.at(1)
	if d := a.at(256) - a.at(128); math.Abs(d-step) > 1e-9 {
		t.Errorf("doubling 1→2 is %g px, 128→256 is %g px; a log scale spaces them equally", step, d)
	}
	if a.at(1) <= 100 || a.at(256) >= 900 {
		t.Errorf("ends at %g and %g, want inside (100, 900) for the padding", a.at(1), a.at(256))
	}
	one := newLog2Axis(8, 8, 0, 100)
	if x := one.at(8); math.Abs(x-50) > 1e-9 {
		t.Errorf("a one-level axis puts it at %g, want the middle (50)", x)
	}
}

