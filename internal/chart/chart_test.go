func TestBarsScaleEachGroupToItsLongestBarAndDrawNoBarWhenMissing(t *testing.T) {
	t.Parallel()
	c := sampleBars()
	got, err := c.SVG()
	if err != nil {
		t.Fatal(err)
	}
	s := string(got)
	// Three drawn bars (b0, b1, b0); the missing B1 has only its label.
	if n := strings.Count(s, `class="b0"`) + strings.Count(s, `class="b1"`) + strings.Count(s, `class="b2"`); n != 3 {
		t.Errorf("%d bars drawn, want 3", n)
	}
	if !strings.Contains(s, "no level meets the SLO") {
		t.Error("the missing bar's label is not drawn")
	}
	// The longest bar in each group ends at the same x: each group has
	// its own scale.
	var ends []string
	for _, line := range strings.Split(s, "\n") {
		if strings.HasPrefix(line, `<path d="M`) && strings.Contains(line, `class="b`) {
			_, rest, _ := strings.Cut(line, "A4 4 0 0 1 ")
			x, _, _ := strings.Cut(rest, " ")
			ends = append(ends, x)
		}
	}
	if len(ends) != 3 || ends[1] != ends[2] {
		t.Errorf("bar ends %v: the B2 bar (group 1) and the throughput baseline (group 2) should both reach the group maximum", ends)
	}
}

