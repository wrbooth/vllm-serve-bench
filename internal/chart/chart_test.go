func TestLinesRejectsWhatItCannotDraw(t *testing.T) {
	t.Parallel()
	cases := map[string]func(*Lines){
		"no panels":   func(c *Lines) { c.Panels = nil },
		"no ticks":    func(c *Lines) { c.XTicks = nil },
		"zero tick":   func(c *Lines) { c.XTicks = []float64{0, 1} },
		"bad slot":    func(c *Lines) { c.Panels[0].Series[0].Slot = Slots },
		"NaN point":   func(c *Lines) { c.Panels[0].Series[0].Points[0].Y = math.NaN() },
		"zero x":      func(c *Lines) { c.Panels[0].Series[0].Points[0].X = 0 },
		"infinite y":  func(c *Lines) { c.Panels[1].Series[0].Points[1].Y = math.Inf(1) },
		"slot below0": func(c *Lines) { c.Panels[0].Series[1].Slot = -1 },
	}
	for name, mutate := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			c := sample()
			c.Panels = slices.Clone(c.Panels)
			for i := range c.Panels {
				c.Panels[i].Series = slices.Clone(c.Panels[i].Series)
				for j := range c.Panels[i].Series {
					c.Panels[i].Series[j].Points = slices.Clone(c.Panels[i].Series[j].Points)
				}
			}
			mutate(&c)
			if _, err := c.SVG(); err == nil {
				t.Error("SVG() accepted it")
			}
		})
	}
}

