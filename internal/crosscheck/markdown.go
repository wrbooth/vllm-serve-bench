// Markdown renders comparison.md. command is the `bench verify` command
// line that produced it, printed in the header so the file says how to
// regenerate itself. The output depends on nothing else, so it is
// byte-identical for the same inputs.
func (c *Comparison) Markdown(command string) []byte {
	var b bytes.Buffer
	p := func(format string, a ...any) { _, _ = fmt.Fprintf(&b, format, a...) }

	p("# Cross-check at concurrency %d: `bench run` vs `vllm bench serve`\n\n", c.Concurrency)
	p("Generated by `bench verify` from the committed files; do not edit by hand.\n")
	p("Regenerate from the repository root (`make build` puts `bench` in `bin/`):\n\n```sh\n%s\n```\n\n", command)
	if c.Valid {
		p("**Valid:** every side prefilled its prompts' unique part (engine-side check below).\n\n")
	} else {
		p("**NOT VALID:** the engine-side check failed; see the warnings. The figures are shown for the record only.\n\n")
		for _, w := range c.Warnings {
			p("> **WARNING:** %s\n>\n", w)
		}
		b.Truncate(b.Len() - 2) // no trailing empty quote line
		p("\n")
	}

	c.table(p)

	p("- vLLM reported: its own figures, numpy-interpolated percentiles. vLLM recomputed: its per-request data with our nearest-rank method (TTFT = ttft; E2E = ttft + Σ itl; TPOT = Σ itl / (output_len − 1), output_len ≥ 2 only). Δ is ours against vLLM recomputed.\n")
	p("- RPS: vLLM recomputed is its steady-state rate (below), since ours excludes ramp-up by warmup; vLLM reported is completed / duration. Output tok/s is over vLLM's whole duration in both vLLM columns.\n")
	p("- Recomputation check, mean recomputed vs reported:")
	for i, m := range c.Means {
		sep := ","
		if i == len(c.Means)-1 {
			sep = "."
		}
		p(" %s %s vs %s ms (%s)%s", m.Metric, f(m.Recomputed, 3), f(m.Reported, 3), pct(m.DeltaPct, 4), sep)
	}
	p("\n\n")

	p("## vLLM start burst\n\n")
	t := c.Burst.TTFT
	p("vLLM's measured run opens with all %d requests sent at once. Without the first %d by send time, its TTFT p50 / p95 / p99 is %s / %s / %s ms (n = %d, nearest-rank). Our warmup absorbs the burst before the window opens.\n\n",
		c.Concurrency, c.Burst.Excluded, f(t.P50, 2), f(t.P95, 2), f(t.P99, 2), t.N)

	p("## Steady-state RPS\n\n")
	s := c.Steady
	if s.OK {
		p("vLLM's sends from first + %s s to last − %s s: %d sends over %s s, (n − 1) / span = **%s req/s**. ",
			f(s.TrimS, -1), f(s.TrimS, -1), s.Sends, f(s.SpanS, 3), f(s.RPS, 3))
	} else {
		p("vLLM's sends from first + %s s to last − %s s: %d in the window, too few for a rate. ", f(s.TrimS, -1), f(s.TrimS, -1), s.Sends)
	}
	p("Its overall request_throughput, ramp-up and drain included, is %s req/s; ours against it:", f(c.VLLMReported.RPS, 3))
	for i := range c.Ours {
		sep := ","
		if i == len(c.Ours)-1 {
			sep = "."
		}
		p(" %s %s%s", c.Ours[i].Label, pctPtr(c.OverallRPSDeltaPct[i], 2), sep)
	}
	p("\n\n")

	c.engineTable(p)
	return b.Bytes()
}

func (c *Comparison) table(p func(string, ...any)) {
	head := make([]string, 0, 1+2*len(c.Ours)+2)
	head = append(head, "Metric")
	for i := range c.Ours {
		head = append(head, c.Ours[i].Label)
	}
	head = append(head, "vLLM reported", "vLLM recomputed")
	for i := range c.Ours {
		head = append(head, "Δ "+c.Ours[i].Label)
	}
	p("| %s |\n|---|%s\n", strings.Join(head, " | "), strings.Repeat("---:|", len(head)-1))
	for i := range c.Rows {
		r := &c.Rows[i]
		cells := []string{r.Metric}
		for _, v := range r.Ours {
			cells = append(cells, f(v, r.digits))
		}
		rec := "–"
		if r.Recomputed != nil {
			rec = f(*r.Recomputed, r.digits)
		}
		cells = append(cells, f(r.Reported, r.digits), rec)
		for j := range r.Ours {
			if r.DeltaPct == nil {
				cells = append(cells, "")
				continue
			}
			cells = append(cells, pctPtr(r.DeltaPct[j], 2))
		}
		p("| %s |\n", strings.Join(cells, " | "))
	}
	p("\n")
}

func (c *Comparison) engineTable(p func(string, ...any)) {
	p("## Engine-side check\n\n")
	p("From each side's `vllm_metrics.csv`: uncached prompt tokens per request = Δ(prefix_cache_queries − prefix_cache_hits) / Δ ttft_count, and engine mean TTFT = Δ ttft_sum / Δ ttft_count. Ours spans the samples covering the measured window; vLLM's, the whole file. A side is invalid below %g × its prompts' unique part: an uncached prompt prefills at least its unique part, a cached one about 1 token.\n\n",
		c.MinUncachedFraction)
	p("| Side | Span | Seconds | TTFT count | Uncached tokens / request | Unique part | Engine mean TTFT (ms) | Status |\n")
	p("|---|---|---:|---:|---:|---:|---:|---|\n")
	for i := range c.Engine {
		e := &c.Engine[i]
		status := "ok"
		if e.Cached {
			status = "**CACHED**"
			if !e.OK {
				status = "**UNVERIFIED**"
			}
		}
		secs, count, uncached, mean := "", "", "", ""
		if e.ToMs != 0 {
			secs = f(float64(e.ToMs-e.FromMs)/1000, 3)
			count = f(e.TTFTCount, 0)
		}
		if e.OK {
			uncached, mean = f(e.UncachedPerRequest, 1), f(e.MeanTTFTms, 2)
		}
		p("| %s | %s | %s | %s | %s | %d | %s | %s |\n", e.Label, e.Span, secs, count, uncached, e.UniqueTokens, mean, status)
	}
}

// f formats with a fixed number of decimals.
func f(v float64, digits int) string { return strconv.FormatFloat(v, 'f', digits, 64) }

// pctPtr is pct, or "–" when the delta is undefined.
func pctPtr(v *float64, digits int) string {
	if v == nil {
		return "–"
	}
	return pct(*v, digits)
}

// pct formats a signed percentage.
func pct(v float64, digits int) string {
	s := f(v, digits)
	if s == "-"+f(0, digits) { // a tiny negative that rounds to zero
		s = s[1:]
	}
	if !strings.HasPrefix(s, "-") {
		s = "+" + s
	}
	return s + "%"
}
